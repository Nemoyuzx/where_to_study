test('actual pinned Tauri ipc/core retain callbacks and request serialization across stock and native routes',async()=>{
  for(const label of ['main','qmplus'])for(const reject of [false,true])for(const payload of [report,'new Uint8Array([4,8]).buffer','({nested:new Map([["fixture",new Uint8Array([6,12])]])})']) {
    const options={actualCore:true,label,reject,page:label==='main'?'http://localhost:5173/':tenant}
    const baseline=fixture({...options,candidate:false,fetchMode:label==='qmplus'?'blocked':'ok'})
    const candidate=fixture({...options,fetchMode:label==='qmplus'?'pending':'ok'})
    const result=f=>f.invoke(payload).then(value=>['resolved',value],error=>['rejected',error])
    assert.deepEqual(await result(candidate),await result(baseline))
    assert.equal(candidate.context.callbackCount(),0)
    assert.equal(baseline.context.callbackCount(),0)
    assert.equal(normalise(candidate.messages),normalise(baseline.messages))
    if(label==='main')assert.equal(normalise(candidate.fetches),normalise(baseline.fetches))
    else assert.equal(candidate.fetches.length,0)
    assert.equal(typeof candidate.context.window.__TAURI_INTERNALS__.transformCallback,'function')
  }
})

