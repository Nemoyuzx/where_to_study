test('native success and rejection both settle existing callbacks and release both IDs',async()=>{
  for(const reject of [false,true]) {
    const f=fixture({reject})
    if(reject)await assert.rejects(f.invoke(report),error=>error==='FIXTURE_REJECTED')
    else assert.equal(await f.invoke(report),true)
    assert.equal(f.context.callbackCount(),0)
    assert.equal(f.messages.length,1)
    assert.equal(f.fetches.length,0)
  }
})

// Binary values below are request payloads. Native raw responses may be JS arrays
// while fetch yields ArrayBuffer; these tests make no response-type equivalence claim.
test('native request envelope preserves stock serialization for binary values, Maps and IPC hooks',async()=>{
  const payloads=[
    ['new Uint8Array([2,4]).buffer',[2,4]],
    ['new Uint8Array([3,6])',[3,6]],
    ['new Map([["fixture",9]])',{fixture:9}],
    ['({__TAURI_TO_IPC_KEY__(){return {fixture:11}}})',{fixture:11}],
    ['({nested:new Uint8Array([5,10]).buffer})',{nested:[5,10]}],
  ]
  for(const [payload,expected] of payloads) {
    const f=fixture()
    await f.invoke(payload,'{headers:{"X-Fixture":"kept"},customProtocolIpcBlocked:false}')
    const message=f.messages[0].message
    assert.deepEqual(message.payload,expected)
    assert.equal(message.cmd,'accept_qmplus_auth')
    assert.deepEqual(message.options,{headers:{'X-Fixture':'kept'},customProtocolIpcBlocked:true})
    assert.equal(f.context.callbackCount(),0)
    const stockFallback=fixture({candidate:false,fetchMode:'blocked'})
    await stockFallback.invoke(payload,'{headers:{"X-Fixture":"kept"},customProtocolIpcBlocked:false}')
    assert.deepEqual(f.messages[0],stockFallback.messages[0])
  }
})

