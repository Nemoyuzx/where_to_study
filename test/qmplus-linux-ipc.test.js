function fixture({candidate=true,label='qmplus',windowLabel=label,page=tenant,fetchMode='ok',reject=false,response=true,os='linux',deferMetadata=false,actualCore=false}={}) {
  const messages=[],fetches=[],warnings=[]
  let context
  const permitted=(url,command)=>label==='main'
    ?new URL(url).origin==='http://localhost:5173'
    :capabilities.some(capability=>capability.windows.includes(windowLabel)
      &&capability.commands.has(command)&&capability.patterns.some(pattern=>pattern.test(url)))
  const reply=(message,allowed)=>{
    if(message.__TAURI_INVOKE_KEY__!=='fixture-invoke-key')throw new Error('fixture invoke key mismatch')
    context.complete(allowed&&!reject?message.callback:message.error,allowed&&!reject?response:'FIXTURE_REJECTED')
  }
  const internals={__TAURI_PATTERN__:{pattern:'brownfield'}}
  if(!actualCore)internals.convertFileSrc=(cmd,protocol)=>`${protocol}://localhost/${encodeURIComponent(cmd)}`
  if(!deferMetadata)internals.metadata={currentWindow:{label:windowLabel},currentWebview:{label}}
  let nextRandom=0
  const window={crypto:{getRandomValues(view){view[0]=++nextRandom;return view}},__TAURI_INTERNALS__:internals,ipc:{postMessage(data){
    const message=JSON.parse(data)
    // Mirrors Wry WebKitGTK: source URI is supplied natively, never from payload.
    messages.push({message,source:page})
    reply(message,permitted(page,message.cmd))
  }}}
  context=vm.createContext({window,Headers,setTimeout,clearTimeout,console:{warn(...args){warnings.push(args.length)}},fetch(url,options){
    fetches.push({url,method:options.method,headers:[...options.headers],body:options.body})
    if(fetchMode==='pending')return new Promise(()=>{})
    if(fetchMode==='blocked')return Promise.reject(new Error('fixture access control'))
    // Mirrors Tauri parse_invoke_request: fetch source comes from Origin only.
    const command=decodeURIComponent(new URL(url).pathname.slice(1))
    const allowed=permitted(new URL(page).origin,command)&&!reject
    return Promise.resolve({headers:new Headers({'Tauri-Response':allowed?'ok':'error','content-type':'application/json'}),json:async()=>allowed?response:'FIXTURE_REJECTED'})
  }})
  vm.runInContext(render(candidate,os),context)
  if(actualCore) {
    vm.runInContext(upstreamIpc.replace('__TEMPLATE_isolation_origin__','"fixture-only"'),context)
    vm.runInContext(upstreamCore.replace('__TEMPLATE_os_name__',JSON.stringify(os)).replace('__TEMPLATE_protocol_scheme__','"http"'),context)
    context.complete=(id,value)=>internals.runCallback(id,value)
    context.callbackCount=()=>internals.callbacks.size
  } else {
  // Tauri's unchanged core owns callback registration and Promise settlement.
  // This synthetic core exercises that public transport contract without a GUI.
  vm.runInContext(`
    const callbacks=new Map();let next=0;
    globalThis.callbackCount=()=>callbacks.size;
    globalThis.complete=(id,value)=>callbacks.get(id)?.(value);
    Object.defineProperty(window.__TAURI_INTERNALS__,'runCallback',{value:complete});
    Object.defineProperty(window.__TAURI_INTERNALS__,'invoke',{value:(cmd,payload={},options)=>new Promise((resolve,reject)=>{
      const callback=++next,error=++next;
      callbacks.set(callback,value=>{callbacks.delete(callback);callbacks.delete(error);resolve(value)});
      callbacks.set(error,value=>{callbacks.delete(error);callbacks.delete(callback);reject(value)});
      window.__TAURI_INTERNALS__.postMessage({cmd,callback,error,payload,options});
    })});
  `,context)
  }
  const invokeCommand=(command,payload='{}',options='undefined')=>vm.runInContext(`window.__TAURI_INTERNALS__.invoke(${JSON.stringify(command)},${payload},${options})`,context)
  return {context,messages,fetches,warnings,run:script=>vm.runInContext(script,context),invokeCommand,invoke:(payload='{}',options='undefined')=>invokeCommand('accept_qmplus_auth',payload,options)}
}
